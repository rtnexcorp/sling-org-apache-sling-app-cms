package org.apache.sling.cms.graphql.internal.dto;

import java.util.List;

/**
 * DTO representing a content fragment for GraphQL response.
 * Contains fragment metadata and generic key-value field structure.
 */
public class ContentFragmentDTO {

    private String id;
    private String name;
    private String schemaId;
    private String title;
    private String created;
    private String modified;
    private String createdBy;
    private String modifiedBy;
    private List<FieldValueDTO> fields;

    public ContentFragmentDTO() {}

    public String getId() {
        return id;
    }

    public void setId(String id) {
        this.id = id;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getSchemaId() {
        return schemaId;
    }

    public void setSchemaId(String schemaId) {
        this.schemaId = schemaId;
    }

    public String getTitle() {
        return title;
    }

    public void setTitle(String title) {
        this.title = title;
    }

    public String getCreated() {
        return created;
    }

    public void setCreated(String created) {
        this.created = created;
    }

    public String getModified() {
        return modified;
    }

    public void setModified(String modified) {
        this.modified = modified;
    }

    public String getCreatedBy() {
        return createdBy;
    }

    public void setCreatedBy(String createdBy) {
        this.createdBy = createdBy;
    }

    public String getModifiedBy() {
        return modifiedBy;
    }

    public void setModifiedBy(String modifiedBy) {
        this.modifiedBy = modifiedBy;
    }

    public List<FieldValueDTO> getFields() {
        return fields;
    }

    public void setFields(List<FieldValueDTO> fields) {
        this.fields = fields;
    }
}
